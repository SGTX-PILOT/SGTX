// ── Helper predicates ───────────────────────────────────────────────────
function isColdChainCommodity(commodityType?: string): boolean {
  if (!commodityType) return false;
  const cold = ["Frozen Fruits", "Frozen Vegetables", "Dairy", "Meat", "Seafood"];
  return cold.some((c) => commodityType.toLowerCase().includes(c.toLowerCase().split(" ")[0]));
}

function isAgriculturalCommodity(commodityType?: string): boolean {
  if (!commodityType) return false;
  const agri = ["Fresh Fruits", "Fresh Vegetables", "Frozen Fruits", "Frozen Vegetables", "Grains"];
  return agri.some((c) => commodityType.toLowerCase().includes(c.toLowerCase().split(" ")[0]));
}

function isFoodCommodity(commodityType?: string): boolean {
  if (!commodityType) return false;
  return isAgriculturalCommodity(commodityType) || ["Dairy", "Meat", "Seafood", "Beverages"].some((c) =>
    commodityType.toLowerCase().includes(c.toLowerCase())
  );
}

function requiresCertOfOrigin(incoterm?: string, destCountry?: string): boolean {
  if (!incoterm) return false;
  // CIF, CIP, DDP, DAP typically require Certificate of Origin
  if (["CIF", "CIP", "DDP", "DAP", "DPU"].includes(incoterm)) return true;
  // Certain destinations always require it
  if (destCountry && ["US", "CA", "EU", "AU"].includes(destCountry)) return true;
  return false;
}

// ── Evaluation engine ────────────────────────────────────────────────────

export interface EvaluatedField extends FieldVisibilityRule {
  visible: boolean;
  reason?: string;
}

/**
 * Evaluate field visibility for the current form state.
 * Returns the list of fields with their visibility + whether they should
 * be rendered.
 *
 * Rules:
 *   - REQUIRED → always visible
 *   - CONDITIONAL → visible only if condition(form) returns true
 *   - OPTIONAL → visible in an "advanced" section (caller decides placement)
 *   - HIDDEN → never visible
 *   - DYNAMIC → visible (the Product Form Agent / RIA engine determines content)
 */
export function evaluateFieldVisibility(form: any): EvaluatedField[] {
  return FIELD_VISIBILITY_RULES.map((rule) => {
    let visible = false;
    let reason: string | undefined;

    switch (rule.visibility) {
      case "REQUIRED":
        visible = true;
        break;
      case "CONDITIONAL":
        visible = rule.condition ? rule.condition(form) : true;
        if (visible && rule.dependsOn && rule.dependsOn.length > 0) {
          reason = `Shown because: ${rule.dependsOn.join(", ")} is set`;
        }
        break;
      case "OPTIONAL":
        visible = true; // visible in advanced section
        reason = "Optional — can be left blank";
        break;
      case "HIDDEN":
        visible = false;
        break;
      case "DYNAMIC":
        visible = true; // the dynamic content engine determines what to render
        reason = "Dynamically generated based on your selections";
        break;
    }

    return { ...rule, visible, reason };
  });
}

/**
 * Get the equipment options for a transport mode.
 * Returns an empty array if the mode is unknown.
 */
export function getEquipmentOptions(transportMode?: string): string[] {
  if (!transportMode) return [];
  return EQUIPMENT_BY_MODE[transportMode] || [];
}

/**
 * Get all visible fields for a given step.
 * Used by the UI to render only the relevant fields per step.
 */
export function getVisibleFieldsForStep(step: number, form: any): EvaluatedField[] {
  return evaluateFieldVisibility(form).filter((f) => f.step === step && f.visible);
}

/**
 * Get the list of fields that are REQUIRED but not yet filled in the form.
 * Used by the Completeness Map + submission gate.
 */
export function getMissingRequiredFields(form: any): { fieldKey: string; label: string; step: number }[] {
  return evaluateFieldVisibility(form)
    .filter((f) => f.visibility === "REQUIRED" && f.visible)
    .filter((f) => {
      const val = (form as any)[f.fieldKey];
      return val === undefined || val === null || val === "" || (Array.isArray(val) && val.length === 0);
    })
    .map((f) => ({ fieldKey: f.fieldKey, label: f.label, step: f.step }));
}
