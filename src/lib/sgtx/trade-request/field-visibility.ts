// SGTX Formal Progressive Dynamic Form — Field Visibility Rules (CCL-004)
// =============================================================================
// Formalizes the existing dynamic field generation as a mandatory UX rule:
// Never display a field unless it is relevant, required, conditionally relevant,
// or deliberately available as an optional advanced field.
//
// Blueprint Part 4 — Buyer Trade Request § "Progressive Dynamic Form"
//
// This module is a PURE visibility-rule engine. It does NOT render fields —
// the UI components consume the rules to decide what to show.

export type FieldVisibility =
  | "REQUIRED" // always show, mandatory
  | "CONDITIONAL" // show only when the condition is met
  | "OPTIONAL" // show in an "advanced" section, not mandatory
  | "HIDDEN" // do not show (not applicable for this trade config)
  | "DYNAMIC"; // generated by the Product Form Agent / RIA engine

export interface FieldVisibilityRule {
  fieldKey: string;
  label: string;
  step: number; // which wizard step (1-11)
  visibility: FieldVisibility;
  condition?: (form: any) => boolean;
  dependsOn?: string[]; // which form fields trigger a re-evaluation
  category?: string; // for grouping in the UI
}

