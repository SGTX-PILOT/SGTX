async function evalFallback(libPath: string): Promise<{ v: CellValue; e: string }> {
  // Heuristic: if lib folder exists and has >1 file, fallback layer likely present
  const p = path.join(PROJECT_ROOT, "src/lib/sgtx", libPath);
  try {
    const entries = await fs.readdir(p);
    if (entries.length > 1) return { v: "PARTIAL", e: `${p} (${entries.length} files)` };
    return { v: "NO", e: "" };
  } catch {
    return { v: "NO", e: "" };
  }
}

