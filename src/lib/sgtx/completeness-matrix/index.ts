function deriveStatus(row: Omit<MatrixRow, "status">): MatrixRow["status"] {
  const cells = ["implemented","database","api","governor","loom","production"] as const;
  const yesCount = cells.filter((c) => row[c] === "YES").length;
  const noCount = cells.filter((c) => row[c] === "NO").length;
  if (yesCount === cells.length) return "OPERATIONAL";
  if (noCount >= cells.length - 1) return "PLANNED";
  if (row.implemented === "PARTIAL" || noCount >= 2) return "PARTIAL";
  return "OPERATIONAL";
}

// ============ §137 Main API ============

export async function generateCompletenessMatrix(): Promise<CompletenessMatrix> {
  try {
    const rows: MatrixRow[] = [];
    for (const entry of SUBSYSTEM_REGISTRY) {
      try {
        const implemented = await evalImplemented(entry.libPath);
        const db = await evalDatabase(entry.libPath);
        const mig = await evalMigration();
        const api = await evalApi(entry.apiPath);
        const openApi = await evalOpenApi();
        const ui = await evalUi(entry.libPath);
        const gov = await evalGovernor();
        const opa = await evalOPA();
        const wasm = await evalWasm();
        const loom = await evalLoom();
        const unit = await evalTests("unit");
        const integ = await evalTests("integration");
        const e2e = await evalTests("e2e");
        const sandbox = await evalSandbox();
        const prod = await evalProduction();
        const fallback = await evalFallback(entry.libPath);
        const admin = await evalAdminVisible();
        const docs = await evalDocumentation();
        const evidence = [
          `lib:${entry.libPath}`, db.e, api.e, gov.e, loom.e,
        ].filter(Boolean).join("; ");
        const row: MatrixRow = {
          subsystem: entry.subsystem,
          implemented,
          database: db.v,
          migration: mig.v,
          api: api.v,
          openApi: openApi.v,
          ui: ui.v,
          governor: gov.v,
          opa: opa.v,
          wasmEdge: wasm.v,
          loom: loom.v,
          unitTest: unit.v,
          integrationTest: integ.v,
          e2eTest: e2e.v,
          sandbox: sandbox.v,
          production: prod.v,
          fallback: fallback.v,
          adminVisible: admin.v,
          documentation: docs.v,
          owner: entry.owner,
          status: "OPERATIONAL",
          evidence: evidence || "no evidence collected",
        };
        row.status = deriveStatus(row);
        rows.push(row);
      } catch (err: any) {
        logger.warn("[completeness-matrix] subsystem eval failed", {
          subsystem: entry.subsystem, error: err?.message,
        });
      }
    }
    const completeCount = rows.filter((r) => r.status === "OPERATIONAL").length;
    const partialCount = rows.filter((r) => r.status === "PARTIAL").length;
    const missingCount = rows.filter((r) => r.status === "PLANNED" || r.implemented === "NO").length;
    logger.info("[completeness-matrix] matrix generated", {
      total: rows.length, completeCount, partialCount, missingCount,
    });
    return {
      subsystems: rows,
      totalSubsystems: rows.length,
      completeCount,
      partialCount,
      missingCount,
      generatedAt: new Date().toISOString(),
    };
  } catch (err: any) {
    logger.error("[completeness-matrix] generate failed", { error: err?.message });
    return {
      subsystems: [], totalSubsystems: 0,
      completeCount: 0, partialCount: 0, missingCount: 0,
      generatedAt: new Date().toISOString(),
    };
  }
}

// ============ §137 Auxiliary: row by subsystem ============

export async function getMatrixRow(subsystem: string): Promise<MatrixRow | null> {
  try {
    const m = await generateCompletenessMatrix();
    return m.subsystems.find((r) => r.subsystem === subsystem) || null;
  } catch {
    return null;
  }
}

