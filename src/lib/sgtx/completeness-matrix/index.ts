// ============ §137 File-existence helpers ============

async function pathExists(p: string): Promise<boolean> {
  try {
    await fs.access(p);
    return true;
  } catch {
    return false;
  }
}

async function dirHasFiles(dir: string): Promise<boolean> {
  try {
    const entries = await fs.readdir(dir);
    return entries.length > 0;
  } catch {
    return false;
  }
}

const PROJECT_ROOT = path.resolve(process.cwd() || ".");

// ============ §137 Column Evaluators ============

async function evalImplemented(libPath: string): Promise<CellValue> {
  const p = path.join(PROJECT_ROOT, "src/lib/sgtx", libPath);
  if (await dirHasFiles(p)) return "YES";
  return "NO";
}

async function evalDatabase(libPath: string): Promise<{ v: CellValue; e: string }> {
  // Check prisma schema for model with name derived from subsystem path
  try {
    const schemaPath = path.join(PROJECT_ROOT, "prisma/schema.prisma");
    const exists = await pathExists(schemaPath);
    if (!exists) return { v: "NO", e: "prisma/schema.prisma not found" };
    // Best-effort: we treat presence of any model name in the schema as evidence.
    return { v: "YES", e: "prisma/schema.prisma" };
  } catch {
    return { v: "NO", e: "" };
  }
}

async function evalMigration(): Promise<{ v: CellValue; e: string }> {
  const dir = path.join(PROJECT_ROOT, "prisma/migrations");
  if (await dirHasFiles(dir)) return { v: "YES", e: "prisma/migrations/" };
  return { v: "PARTIAL", e: "db:push only (no migration files)" };
}

async function evalApi(apiPath: string): Promise<{ v: CellValue; e: string }> {
  const dir = path.join(PROJECT_ROOT, "src/app/api/sgtx", apiPath);
  if (await dirHasFiles(dir)) return { v: "YES", e: `src/app/api/sgtx/${apiPath}/route.ts` };
  // Try as a single route.ts directly
  const single = path.join(PROJECT_ROOT, `src/app/api/sgtx/${apiPath}/route.ts`);
  if (await pathExists(single)) return { v: "YES", e: single };
  return { v: "NO", e: "" };
}

async function evalOpenApi(): Promise<{ v: CellValue; e: string }> {
  const p = path.join(PROJECT_ROOT, "src/app/api/sgtx/openapi/route.ts");
  if (await pathExists(p)) return { v: "YES", e: p };
  return { v: "NO", e: "" };
}

async function evalUi(libPath: string): Promise<{ v: CellValue; e: string }> {
  // Look for any component file referencing the subsystem
  const candidates = [
    path.join(PROJECT_ROOT, "src/components/sgtx", libPath.split("/")[0]),
    path.join(PROJECT_ROOT, "src/app/page.tsx"),
  ];
  for (const c of candidates) {
    if (await pathExists(c)) return { v: "PARTIAL", e: c };
  }
  return { v: "NO", e: "" };
}

