/**
 * SGTX Part 137 — Final Completeness Matrix
 * ===========================================================================
 *
 * Single source of truth for the 175-part Master Global Trade Completion
 * acceptance matrix. For each subsystem, evaluates 22 columns:
 *
 *   Subsystem | Implemented | Database | Migration | API | OpenAPI | UI |
 *   Governor | OPA | WasmEdge | Loom | UnitTest | IntegrationTest | E2ETest |
 *   Sandbox | Production | Fallback | AdminVisible | Documentation | Owner |
 *   Status | Evidence
 *
 * Per §137: NO cell may carry the value UNKNOWN at final acceptance. Every
 * cell must be YES / NO / PARTIAL with an Evidence string linking to the
 * file path, prisma model, API route, or test file that proves the value.
 *
 * The matrix is generated by scanning the actual codebase: existence of
 * files in src/lib/sgtx/<subsystem>/, src/app/api/sgtx/<subsystem>/, the
 * Prisma schema, and the governor/loom/opa/wasm folders. Where a column
 * cannot be auto-detected (Documentation, Owner), it falls back to the
 * hard-coded registry below.
 *
 * All file-system reads are try/catch-wrapped with safe defaults. The
 * generator never throws.
 */

