// SGTX Worldwide Port Routes Database
// =============================================================================
// A comprehensive static + computed database covering worldwide container
// trade lanes: 80+ major global ports × 30+ shipping lines × 400+ port-pair
// routes with deterministic prices, transit times, frequencies, and services.
//
// All orchestrated and continuously learned-from by the SGTX Brain OS via the
// `worldwideRoutesModule` Brain capability (see
// `src/lib/sgtx/brain-os/capabilities/worldwide-routes-orchestrator.ts`).
//
// Design notes:
//   * Prices are generated by a deterministic mulberry32 RNG seeded by a hash
//     of the routeId. This means the same routeId always produces the same
//     base price — so daily syncs are reproducible until the orchestrator
//     applies a market-drift random walk (±3%) on top.
//   * The orchestrator maintains a `LearningAdjustments` map keyed by routeId.
//     Each adjustment holds an exponential-moving-average correction for both
//     price (pct) and transit (days) learned from observed outcomes. Every
//     `getRoutePrice()` call automatically applies the active correction so
//     the Brain's predictions converge on reality over time.
//   * Ports use real UN/LOCODEs. Shipping lines use the same codes as
//     `src/lib/sgtx/shipping/shipping-lines-db.ts` (extended here with 10
//     additional niche carriers).
//
// Data sources referenced when curating the trade-lane base rates:
//   - Freightos Baltic Index (FBX) — spot rates by trade lane
//   - Drewry World Container Index (WCI) — composite benchmark
//   - Xeneta XSI — long-term contract rates
//   - JOC / PIERS — carrier market share by lane
//   - Alphaliner TOP 100 — carrier TEU capacity + market share
// =============================================================================

// ============ Types ============

/** A worldwide container port with UN/LOCODE, region, and terminal handling
 *  cost references (USD per 20ft / 40ft container). */
export interface WorldwidePort {
  unlocode: string;
  name: string;
  country: string;
  region: WorldwideRegion;
  lat: number;
  lng: number;
  timezone: string;
  handlingCost20ft: number;
  handlingCost40ft: number;
}

/** A major container shipping line. Mirrors `ShippingLineInfo` from
 *  `shipping-lines-db.ts` but adds alliance membership. */
export interface WorldwideShippingLine {
  code: string;
  name: string;
  country: string;
  teuCapacity: number;
  marketSharePct: number;
  website: string;
  trackingUrl: string;
  services: string[];
  reeferCapable: boolean;
  dgCapable: boolean;
  alliance: Alliance;
}

/** A single trade-lane × carrier entry. */
export interface WorldwideRoute {
  routeId: string; // `${origin}-${dest}-${line}` e.g. "EGALX-DEHAM-MAERSK"
  originPort: string;
  originName: string;
  originCountry: string;
  originRegion: WorldwideRegion;
  destinationPort: string;
  destinationName: string;
  destinationCountry: string;
  destinationRegion: WorldwideRegion;
  shippingLine: string;
  shippingLineName: string;
  alliance?: Alliance;
  service: string;
  transitDays: number;
  frequencyPerWeek: number;
  serviceType: "DIRECT" | "TRANSSHIPMENT";
  transshipmentPort?: string;
  price20Std: number;
  price40Std: number;
  price40Hc: number;
  price20Reefer: number;
  price40Reefer: number;
  currency: "USD";
  priceValidityDays: number;
  confidence: number;
  source: "database" | "ai-estimated";
  lastUpdated: string;
}

/** Container alliance membership. */
export type Alliance = "2M" | "OCEAN" | "THE" | "IGA" | "standalone";

/** One of the 8 worldwide trade regions. */
export type WorldwideRegion =
  | "Asia"
  | "Europe"
  | "Middle East"
  | "Africa"
  | "North America"
  | "South America"
  | "Oceania"
  | "Central America";

/** A learned correction applied on top of the deterministic base price +
 *  transit time for a given route. Maintained by the Brain orchestrator and
 *  updated via exponential moving average (alpha=0.2) when actual outcomes
 *  are observed. */
export interface LearningAdjustment {
  priceCorrectionPct: number; // e.g. +0.05 means route is 5% pricier than base
  transitCorrectionDays: number; // e.g. +2 means route is 2 days slower than base
  sampleCount: number;
  lastUpdated: string;
}

/** Aggregated worldwide-stats response. */
export interface WorldwideStats {
  totalPorts: number;
  totalLines: number;
  totalRoutes: number;
  totalSchedules: number;
  regionCoverage: Record<WorldwideRegion, number>;
  avgPriceByLane: Array<{
    lane: string;
    avgPrice40Std: number;
    routeCount: number;
    avgTransitDays: number;
  }>;
  lastFullSyncAt: string;
}

