/**
 * Get all routes matching an origin/destination pair. Optionally filter by
 * shipping line.
 */
export function getRoutesByLane(origin: string, dest: string, line?: string): WorldwideRoute[] {
  const o = origin.toUpperCase();
  const d = dest.toUpperCase();
  const l = line?.toUpperCase();
  return getAllRoutes().filter(
    (r) => r.originPort === o && r.destinationPort === d && (!l || r.shippingLine === l),
  );
}

/**
 * Get the active price ladder for a single route, applying any learning
 * correction currently stored in `ROUTE_ADJUSTMENTS`. Returns the route's
 * stored prices adjusted by `priceCorrectionPct` (rounded to nearest USD).
 *
 * Transit corrections are applied to `transitDays` in `getRouteTransit()` —
 * they are NOT applied here because the price ladder doesn't carry transit.
 */
export function getRoutePrice(route: WorldwideRoute): {
  price20Std: number;
  price40Std: number;
  price40Hc: number;
  price20Reefer: number;
  price40Reefer: number;
  currency: "USD";
  appliedCorrectionPct: number;
} {
  const adj = ROUTE_ADJUSTMENTS.get(route.routeId);
  const factor = adj ? 1 + adj.priceCorrectionPct : 1;
  const apply = (n: number) => (n > 0 ? Math.max(1, Math.round(n * factor)) : 0);
  return {
    price20Std: apply(route.price20Std),
    price40Std: apply(route.price40Std),
    price40Hc: apply(route.price40Hc),
    price20Reefer: apply(route.price20Reefer),
    price40Reefer: apply(route.price40Reefer),
    currency: "USD",
    appliedCorrectionPct: adj ? adj.priceCorrectionPct : 0,
  };
}

/**
 * Get the active transit-time estimate for a single route, applying any
 * learning correction currently stored in `ROUTE_ADJUSTMENTS`. Returns the
 * route's stored transitDays adjusted by `transitCorrectionDays` (clamped to
 * a minimum of 1 day).
 */
export function getRouteTransit(route: WorldwideRoute): {
  transitDays: number;
  appliedCorrectionDays: number;
} {
  const adj = ROUTE_ADJUSTMENTS.get(route.routeId);
  const correction = adj ? adj.transitCorrectionDays : 0;
  return {
    transitDays: Math.max(1, Math.round(route.transitDays + correction)),
    appliedCorrectionDays: correction,
  };
}

// ============ Stats ============

/**
 * Compute aggregated worldwide stats: total ports, lines, routes, schedules
 * (routes × weekly frequency), region coverage, and average price by trade
 * lane. Used by the Brain orchestrator's `logistics.worldwide-routes-stats`
 * capability and surfaced to dashboards.
 */
export function getWorldwideStats(): WorldwideStats {
  const routes = getAllRoutes();
  const portCodes = new Set<string>();
  const lineCodes = new Set<string>();
  const regionCoverage: Record<WorldwideRegion, number> = {
    Asia: 0,
    Europe: 0,
    "Middle East": 0,
    Africa: 0,
    "North America": 0,
    "South America": 0,
    Oceania: 0,
    "Central America": 0,
  };
  let totalSchedules = 0;
  const laneMap = new Map<string, { sum40: number; count: number; sumDays: number }>();

  for (const r of routes) {
    portCodes.add(r.originPort);
    portCodes.add(r.destinationPort);
    lineCodes.add(r.shippingLine);
    regionCoverage[r.originRegion]++;
    regionCoverage[r.destinationRegion]++;
    totalSchedules += r.frequencyPerWeek;
    const laneKey = `${r.originRegion}→${r.destinationRegion}`;
    const entry = laneMap.get(laneKey) ?? { sum40: 0, count: 0, sumDays: 0 };
    entry.sum40 += r.price40Std;
    entry.sumDays += r.transitDays;
    entry.count++;
    laneMap.set(laneKey, entry);
  }

  const avgPriceByLane = Array.from(laneMap.entries())
    .map(([lane, agg]) => ({
      lane,
      avgPrice40Std: Math.round(agg.sum40 / agg.count),
      routeCount: agg.count,
      avgTransitDays: Math.round(agg.sumDays / agg.count),
    }))
    .sort((a, b) => b.routeCount - a.routeCount);

  return {
    totalPorts: portCodes.size,
    totalLines: lineCodes.size,
    totalRoutes: routes.length,
    totalSchedules,
    regionCoverage,
    avgPriceByLane,
    lastFullSyncAt: LAST_FULL_SYNC_AT,
  };
}

