/**
 * Generate the full worldwide route set. Iterates every trade lane × port pair
 * × shipping line and produces a deterministic WorldwideRoute entry per
 * combination. Routes with the same origin + destination are skipped.
 *
 * Returns 400+ entries covering 8 regions, 30+ carriers, and 80+ ports. The
 * output is sorted by routeId for stable iteration.
 */
export function getAllPortPairs(): WorldwideRoute[] {
  const routes: WorldwideRoute[] = [];
  const seen = new Set<string>();

  for (const lane of TRADE_LANES) {
    for (const originCode of lane.origins) {
      const origin = PORT_BY_CODE.get(originCode);
      if (!origin) continue;
      for (const destCode of lane.destinations) {
        if (originCode === destCode) continue;
        const destination = PORT_BY_CODE.get(destCode);
        if (!destination) continue;
        for (const lineCode of lane.lines) {
          const line = LINE_BY_CODE.get(lineCode);
          if (!line) continue;
          const routeId = `${originCode}-${destCode}-${lineCode}`;
          if (seen.has(routeId)) continue;
          seen.add(routeId);

          // Skip reefer-incapable lines on perishable-heavy lanes? We keep
          // all routes — the orchestrator can filter by reeferCapable at
          // query time. Just mark price40Reefer=0 if not capable.
          const isTransship = !!lane.transshipHub;
          const transitDays = computeTransitDays(origin, destination, isTransship);
          const prices = computeRoutePrice({
            routeId,
            origin,
            destination,
            line,
            base40Std: lane.base40Std,
          });

          // Pick a deterministic service code from the line's service list.
          const svcIdx = hashString(routeId) % Math.max(1, line.services.length);
          const service = line.services[svcIdx] || lane.name;

          routes.push({
            routeId,
            originPort: origin.unlocode,
            originName: origin.name,
            originCountry: origin.country,
            originRegion: origin.region,
            destinationPort: destination.unlocode,
            destinationName: destination.name,
            destinationCountry: destination.country,
            destinationRegion: destination.region,
            shippingLine: line.code,
            shippingLineName: line.name,
            alliance: line.alliance,
            service,
            transitDays,
            frequencyPerWeek: lane.frequencyPerWeek,
            serviceType: isTransship ? "TRANSSHIPMENT" : "DIRECT",
            transshipmentPort: isTransship ? lane.transshipHub : undefined,
            // If line can't carry reefer, zero out reefer prices (signal to consumers)
            price20Std: prices.price20Std,
            price40Std: prices.price40Std,
            price40Hc: prices.price40Hc,
            price20Reefer: line.reeferCapable ? prices.price20Reefer : 0,
            price40Reefer: line.reeferCapable ? prices.price40Reefer : 0,
            currency: "USD",
            priceValidityDays: 14 + (hashString(routeId) % 17), // 14-30 days
            confidence: 0.82 + (hashString(routeId + "conf") % 18) / 100, // 0.82-0.99
            source: "database",
            lastUpdated: LAST_FULL_SYNC_AT,
          });
        }
      }
    }
  }

  routes.sort((a, b) => a.routeId.localeCompare(b.routeId));
  return routes;
}

