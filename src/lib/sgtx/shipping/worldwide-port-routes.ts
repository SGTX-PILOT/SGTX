const HC_PREMIUM = 1.05;

/**
 * Haversine distance between two lat/lng points, in kilometers. Used as the
 * distance multiplier in the pricing model (longer routes = pricier) and to
 * derive baseline transit days (vessel avg ~22 km/h → ~528 km/day).
 */
export function haversineKm(a: WorldwidePort, b: WorldwidePort): number {
  const R = 6371; // km
  const toRad = (d: number) => (d * Math.PI) / 180;
  const dLat = toRad(b.lat - a.lat);
  const dLng = toRad(b.lng - a.lng);
  const s =
    Math.sin(dLat / 2) ** 2 +
    Math.cos(toRad(a.lat)) * Math.cos(toRad(b.lat)) * Math.sin(dLng / 2) ** 2;
  return 2 * R * Math.asin(Math.sqrt(s));
}

/**
 * Carrier market-share premium. Carriers with higher market share charge a
 * small reliability premium (up to ~8% for the top carrier, scaling down
 * linearly). Niche carriers (<0.5% share) get a small discount.
 */
function carrierPremium(marketSharePct: number): number {
  if (marketSharePct >= 15) return 1.08;
  if (marketSharePct >= 10) return 1.05;
  if (marketSharePct >= 5) return 1.02;
  if (marketSharePct >= 1) return 1.0;
  if (marketSharePct >= 0.5) return 0.97;
  return 0.94;
}

/**
 * Compute the full price ladder (20'STD / 40'STD / 40'HC / 20'RF / 40'RF) for
 * a route. The model multiplies the lane base rate by:
 *   1. A distance multiplier (route distance / 5000km, clamped to 0.6-2.0)
 *   2. A carrier market-share premium (0.94 - 1.08)
 *   3. A deterministic ±8% jitter seeded by routeId hash
 *   4. A reefer premium (1.7×) for reefer types
 *   5. An HC premium (1.05×) for 40'HC
 * Returns integer USD per container.
 *
 * The deterministic jitter is the *only* randomness — the same routeId always
 * produces the same base price. The orchestrator's `syncWorldwideRoutes()`
 * applies an additional ±3% daily market-drift random walk on top.
 */
export function computeRoutePrice(input: {
  routeId: string;
  origin: WorldwidePort;
  destination: WorldwidePort;
  line: WorldwideShippingLine;
  base40Std: number;
}): { price20Std: number; price40Std: number; price40Hc: number; price20Reefer: number; price40Reefer: number } {
  const distance = haversineKm(input.origin, input.destination);
  const distanceMultiplier = Math.max(0.6, Math.min(2.0, distance / 5000));
  const premium = carrierPremium(input.line.marketSharePct);

  const rng = mulberry32(hashString(input.routeId));
  // Deterministic ±8% jitter
  const jitter = 1 + (rng() * 0.16 - 0.08);

  const base40Std = Math.round(input.base40Std * distanceMultiplier * premium * jitter);
  const price40Std = Math.max(150, base40Std);
  const price40Hc = Math.round(price40Std * HC_PREMIUM);
  const price20Std = Math.round(price40Std * PRICE_FACTORS.std20);
  const price40Reefer = Math.round(price40Std * REEFER_PREMIUM);
  const price20Reefer = Math.round(price20Std * REEFER_PREMIUM);

  return { price20Std, price40Std, price40Hc, price20Reefer, price40Reefer };
}

/**
 * Compute transit days from great-circle distance. Vessel effective speed
 * averages ~22 km/h (~528 km/day), but trunk-lane vessels are faster. Add 2
 * days for transshipment legs.
 */
export function computeTransitDays(origin: WorldwidePort, destination: WorldwidePort, transshipment?: boolean): number {
  const distance = haversineKm(origin, destination);
  const effectiveKmPerDay = 480; // accounts for canal/transit/port-call overhead
  const base = Math.max(2, Math.round(distance / effectiveKmPerDay));
  return transshipment ? base + 2 : base;
}

