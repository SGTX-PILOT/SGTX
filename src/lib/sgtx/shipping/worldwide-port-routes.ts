// ============ Deterministic RNG ============

/**
 * Hash a string into a 32-bit unsigned int (FNV-1a variant). Used to seed the
 * mulberry32 RNG so each routeId produces a deterministic price series.
 */
function hashString(str: string): number {
  let h = 0x811c9dc5;
  for (let i = 0; i < str.length; i++) {
    h ^= str.charCodeAt(i);
    h = Math.imul(h, 0x01000193);
  }
  return h >>> 0;
}

/**
 * Mulberry32 — small, fast, deterministic 32-bit PRNG. Returns a thunk that
 * produces floats in [0, 1) on each call.
 */
function mulberry32(seed: number): () => number {
  let a = seed >>> 0;
  return function () {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

